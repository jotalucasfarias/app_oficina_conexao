-- Execute este script no SQL Editor do projeto Supabase escolhido.
-- A tabela aceita somente inserções públicas para este teste.
-- Não há política pública de leitura dos registros.

create table if not exists public.nomes_teste (
  id bigint generated by default as identity primary key,
  nome text not null check (char_length(trim(nome)) between 1 and 120),
  criado_em timestamptz not null default now()
);

alter table public.nomes_teste enable row level security;

grant insert on table public.nomes_teste to anon;
grant usage, select on sequence public.nomes_teste_id_seq to anon;

drop policy if exists "Permitir cadastro público de nomes de teste" on public.nomes_teste;

create policy "Permitir cadastro público de nomes de teste"
on public.nomes_teste
for insert
to anon
with check (char_length(trim(nome)) between 1 and 120);